import { Meters, ParameterControls, PresetSelect, useAudioSource, useAudiospanHost, usePlugin } from "@audiospan/react";
import type { GainCppPlugin } from "../plugins/gain/plugin.js"; // generated by `audiospan build`, copied with the artifact

const PLUGIN_URL = new URL("./plugins/gain/plugin.json", document.baseURI).href;

export function App() {
  // No workletUrl: the SDK loads its embedded worklet. The hook owns the AudioContext and the host.
  const audio = useAudiospanHost({ onError: (error) => console.error(error.code, error.message) });
  // Loads the plugin, creates an instance, and puts it in the chain once the host is running. Ids are typed.
  const gain = usePlugin<GainCppPlugin>(audio.host, PLUGIN_URL);
  // Feed the chain from an oscillator while running; "microphone" or an <audio> element work the same way.
  const source = useAudioSource(audio, (context) => {
    const oscillator = context.createOscillator();
    oscillator.frequency.value = 220;
    const level = context.createGain();
    level.gain.value = 0.2;
    oscillator.connect(level);
    oscillator.start();
    return level;
  });

  const error = audio.error ?? gain.error ?? source.error;
  return (
    <main>
      <h1>Audiospan React example</h1>
      <p>Three hooks from @audiospan/react own the host, the plugin and the source; the controls and meters below are React components bound to the plugin.</p>
      <div>
        <button type="button" onClick={() => void audio.start()} disabled={audio.status === "running" || audio.status === "starting"}>
          Start audio
        </button>{" "}
        <button type="button" onClick={() => void audio.stop()} disabled={audio.status !== "running"}>
          Stop
        </button>{" "}
        <button type="button" onClick={() => gain.setBypassed(!gain.bypassed)} disabled={gain.status !== "ready"} aria-pressed={gain.bypassed}>
          {gain.bypassed ? "Bypassed" : "Bypass"}
        </button>{" "}
        <PresetSelect plugin={gain} />
      </div>
      <div role="status">
        {audio.status === "starting" && "Loading…"}
        {audio.status === "running" && gain.status === "loading" && "Loading plugin…"}
        {audio.status === "running" && gain.descriptor && `Running ${gain.descriptor.name} ${gain.descriptor.version}`}
        {audio.status === "idle" && "Idle."}
        {audio.status === "error" && "Failed."}
      </div>
      {error && <div className="error">{`${"code" in error ? `${error.code}: ` : ""}${error.message}`}</div>}
      <ParameterControls plugin={gain} />
      <Meters plugin={gain} />
      <p>Cutoff-style typed access: gain = {gain.values.gain?.toFixed(2) ?? "…"}, level = {gain.outputs.level?.toFixed(2) ?? "…"}</p>
    </main>
  );
}

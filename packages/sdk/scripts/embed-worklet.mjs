// Embed the built worklet (packages/runtime/dist/audiospan-worklet.js) into the
// SDK as a string, so AudiospanHost.create() can load it from a blob URL when
// the application passes no workletUrl. Runs before `tsc` (see the root
// package.json scripts); the output is generated and not committed.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL("..", import.meta.url));
const source = readFileSync(`${here}../runtime/dist/audiospan-worklet.js`, "utf8");
mkdirSync(`${here}src/generated`, { recursive: true });
writeFileSync(
  `${here}src/generated/worklet-source.ts`,
  `// Generated by scripts/embed-worklet.mjs from @audiospan/runtime/dist/audiospan-worklet.js. Do not edit.\n` +
    `export const WORKLET_SOURCE: string = ${JSON.stringify(source)};\n`,
);
console.log(`embedded worklet (${source.length} chars) into packages/sdk/src/generated/worklet-source.ts`);
